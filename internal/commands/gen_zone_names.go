//go:build ignore

// gen_zone_names writes zone_names.go from the zone database Go embeds as
// time/tzdata, which ships beside it as the zip named on the command line.
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
)

func main() {
	r, err := zip.OpenReader(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	defer r.Close()
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_zone_names.go; DO NOT EDIT.\n\npackage commands\n\n")
	b.WriteString("// zoneNames are the zones of the time/tzdata Go's Windows build embeds.\nvar zoneNames = []string{\n")
	for _, f := range r.File {
		fmt.Fprintf(&b, "%q,\n", f.Name)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("zone_names.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
